"""Database layer: PostgreSQL via psycopg, no ORM needed for this scope."""

import threading

import psycopg

from .config import settings

_local = threading.local()


def get_connection() -> psycopg.Connection:
    """Return a per-thread PostgreSQL connection."""
    conn = getattr(_local, "conn", None)
    if conn is None:
        conn = psycopg.connect(
            host=settings.db_host,
            port=settings.db_port,
            dbname=settings.db_name,
            user=settings.db_user,
            password=settings.db_password,
            autocommit=True,
        )
        _local.conn = conn
    return conn


def init_db() -> None:
    conn = get_connection()
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS teams (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            name_folded TEXT NOT NULL,
            ctf_experience TEXT NOT NULL DEFAULT 'regular'
                CHECK (ctf_experience IN ('regular', 'ai')),
            created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            CONSTRAINT teams_name_folded_key UNIQUE (name_folded)
        )
        """
    )
    conn.execute(
        """
        CREATE TABLE IF NOT EXISTS members (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            team_id BIGINT NOT NULL REFERENCES teams(id) ON DELETE CASCADE,
            username TEXT NOT NULL,
            username_folded TEXT NOT NULL,
            order_code TEXT NOT NULL DEFAULT '',
            joined_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
            CONSTRAINT members_team_id_username_folded_key
                UNIQUE (team_id, username_folded)
        )
        """
    )
    # An attendee email can belong to only one team, not merely appear
    # once within each individual team.
    conn.execute(
        """
        CREATE UNIQUE INDEX IF NOT EXISTS idx_members_username_folded
            ON members(username_folded)
        """
    )
    conn.execute(
        "CREATE INDEX IF NOT EXISTS idx_members_team ON members(team_id)"
    )


def reset_db() -> None:
    """Drop and recreate all tables (used by tests)."""
    conn = get_connection()
    with conn.transaction():
        conn.execute("DROP TABLE IF EXISTS members")
        conn.execute("DROP TABLE IF EXISTS teams")
    init_db()
